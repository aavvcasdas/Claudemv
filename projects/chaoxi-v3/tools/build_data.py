#!/usr/bin/env python3
"""Build browser data from the plan and analyses; no duplicated timing constants."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def build(root=ROOT):
    plan=json.loads((root/'plan.json').read_text())
    analysis=json.loads((root/'analysis/report.json').read_text())
    captions=json.loads((root/'assets/captions.json').read_text()) if (root/'assets/captions.json').exists() else {'rows':[]}
    data={'shots':plan['shots'],'beats':analysis['audio']['beats'],'captions':captions['rows'],'captions_enabled':plan['captions']['enabled']}
    text='// Generated by tools/build_data.py; source: plan.json + actual MP4 analyses.\nconst FILM_DATA = '+json.dumps(data,ensure_ascii=False,indent=2)+';\n'
    (root/'src/project-data.js').write_text(text)
    return data
if __name__=='__main__':
    d=build();print(f"Built {len(d['shots'])} shots, {len(d['captions'])} captions, {len(d['beats'])} measured beats")
